/* The old product name -> dika studio, for the Community Editor ONLY, and it renames NAMES only.
 *
 * (This file renamed ITSELF on the run: the sentence above used to spell the old name twice and now
 * reads "dika studio -> dika studio". Left as a note rather than quietly patched, because it is the
 * clearest possible demonstration that the replacement is indiscriminate about context and why the
 * PROTECTED list below is the only thing standing between it and somebody's data.)
 *
 * The owner asked for the whole product renamed and then narrowed it to the community build. The
 * inventory (docs/dika-studio-rename-inventory.md) found that most `cardcraft` occurrences in this
 * tree are not names at all: they are the keys somebody's work is stored under. Renaming one of
 * those does not change a label, it makes a person open the app to an empty canvas.
 *
 * SO THIS SCRIPT REPLACES EXACTLY TWO PATTERNS:
 *     \bCardCraft\b   ->  dika studio
 *     \bCARDCRAFT\b   ->  DIKA STUDIO
 *
 * and the word boundary is doing the real work. `_` is a word character in a regex, so:
 *     CardCraftFontLibrary   no match (F follows the boundary-less T)
 *     CARDCRAFT_CUSTOM_PROPS no match (_ follows)
 *     cardcraft_autosave     no match (lowercase, and _ follows)
 *     .cardcraft             no match (lowercase)
 * Every identifier in the PROTECTED list below is therefore untouched BY CONSTRUCTION rather than by
 * a filter somebody has to maintain. The list is still asserted after the write, because "by
 * construction" is a claim and this one is worth checking.
 *
 * NOT RENAMED, deliberately, each with a reason:
 *   .cardcraft                      designs people have already saved. Moving the SAVE default is a
 *                                   migration that must keep READING the old one, in its own phase.
 *   cardcraft_* (about 50 keys)     the editor's whole local state: autosave, version history,
 *                                   brand sets, templates, gallery, video projects, settings.
 *   cardcraft-community,            four IndexedDB names. A renamed database is an empty new one.
 *   CardCraftPagesDB, ...FontsDB,
 *   ...TemplatesDB
 *   design.cardcraft.community      electron-builder appId: Windows and macOS key an UPGRADE on it.
 *   window.saveCardcraftNow,        editor globals in a build with no bundler, referenced from
 *   CardCraftFontLibrary,           onclick= attributes and string lookups as well as from code.
 *   CardCraftRecorder,
 *   CardCraftEmailVerify,
 *   CardCraftMyShapes,
 *   CARDCRAFT_CUSTOM_PROPS,
 *   _CARDCRAFT_SEED_RECIPES
 *   application/x-cardcraft-*       drag and drop MIME types; both sides must move together.
 *   cardcraft-saved-indicator, ...  DOM ids and CSS classes.
 *   cardcraft-standard              a stored DB value with rows behind it.
 *   cardcraft-editor-bundle-v2      the bundle hash salt.
 *   cardcraft-community-desktop     the npm package name (not user-visible; productName is).
 *
 *   node tools/rename-to-dika-studio.mjs           # dry run, prints every file and count
 *   node tools/rename-to-dika-studio.mjs --apply
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, extname, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOTS = [join(HERE, '..'), join(HERE, '..', '..', 'community-desktop')];
const APPLY = process.argv.includes('--apply');

/* Directories that hold generated or third-party bytes. `dist/` matters most: index.html and the
   module bundle are GENERATED from the sources this script edits, so editing them here would be
   overwritten by the next build and would make the drift check disagree with itself. */
const SKIP_DIRS = new Set(['node_modules', 'dist', 'vendor', '.git', 'tests']);
const TEXT = new Set([
  '.js', '.mjs', '.cjs', '.ts', '.json', '.html', '.css', '.md', '.txt', '.yml', '.yaml', '.svg'
]);

/* index.html is generated by tools/build-bundle.mjs from index.dev.html. LICENSE is the BUSL text
   itself and names the licensed work; changing it is a legal decision, not a rename (inventory §A). */
const SKIP_FILES = new Set(['index.html', 'LICENSE']);

const PROTECTED = [
  '.cardcraft', 'cardcraft_', 'cardcraft-community', 'CardCraftPagesDB', 'CardCraftFontsDB',
  'CardCraftTemplatesDB', 'design.cardcraft.community', 'saveCardcraftNow', 'CardCraftFontLibrary',
  'CardCraftRecorder', 'CardCraftEmailVerify', 'CardCraftMyShapes', 'CARDCRAFT_CUSTOM_PROPS',
  '_CARDCRAFT_SEED_RECIPES', 'application/x-cardcraft', 'cardcraft-saved-indicator',
  'cardcraft-standard', 'cardcraft-editor-bundle-v2', 'cardcraft-community-desktop',
  'restoreCardcraftAutosave', 'clearCardcraftAutosaveKey', 'CARDCRAFT_PORT'
];

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (TEXT.has(extname(name)) && !SKIP_FILES.has(basename(name))) out.push(p);
  }
  return out;
}

const before = new Map();   // protected token -> count across the tree, measured BEFORE
const after = new Map();
const changed = [];
let total = 0;

function countProtected(files, into) {
  for (const t of PROTECTED) into.set(t, 0);
  for (const f of files) {
    const s = readFileSync(f, 'utf8');
    for (const t of PROTECTED) {
      let n = 0, i = 0;
      while ((i = s.indexOf(t, i)) !== -1) { n++; i += t.length; }
      if (n) into.set(t, into.get(t) + n);
    }
  }
}

const files = ROOTS.flatMap((r) => walk(r));
countProtected(files, before);

for (const f of files) {
  const src = readFileSync(f, 'utf8');
  const out = src.replace(/\bCardCraft\b/g, 'dika studio').replace(/\bCARDCRAFT\b/g, 'DIKA STUDIO');
  if (out === src) continue;
  const n = (src.match(/\bCardCraft\b|\bCARDCRAFT\b/g) || []).length;
  total += n;
  changed.push({ file: relative(join(HERE, '..', '..'), f).replace(/\\/g, '/'), replacements: n });
  if (APPLY) writeFileSync(f, out);
}

if (APPLY) countProtected(files, after);

/* THE ASSERTION THAT MATTERS: every protected identifier must be present exactly as often after the
   write as before it. A word-boundary regex should make that true by construction; this is what
   turns "should" into "did". */
const drift = APPLY
  ? PROTECTED.filter((t) => before.get(t) !== after.get(t))
      .map((t) => `${t}: ${before.get(t)} -> ${after.get(t)}`)
  : [];

console.log(JSON.stringify({
  mode: APPLY ? 'APPLIED' : 'dry run, nothing written',
  filesScanned: files.length,
  filesChanged: changed.length,
  replacements: total,
  protectedIdentifiers: Object.fromEntries([...before].filter(([, n]) => n > 0)),
  protectedDrift: drift,
  top: changed.sort((a, b) => b.replacements - a.replacements).slice(0, 12)
}, null, 1));

if (drift.length) { console.error('PROTECTED IDENTIFIER CHANGED. Restore from the backup zip.'); process.exit(1); }
